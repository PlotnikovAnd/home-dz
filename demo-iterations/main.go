package main

import "fmt"

// **Описание**: Напишите программу, которая находит первое число в диапазоне и досрочно прерывает перебор с помощью цикла for и оператора break.
//
// **Входные данные**: Две переменные типа int, уже объявленные в коде: start со значением 10 и divisor со значением 7. Нужно перебирать числа, начиная с start и увеличивая на 1.
//
// **Выходные данные**: Выведите в консоль первое число (начиная со start), которое делится на divisor без остатка, в формате: "Первое число: X". Как только такое число найдено, перебор нужно немедленно прекратить.
//
// **Ограничения**: Обязательно используйте цикл for и оператор break для остановки перебора после нахождения подходящего числа. Перебирайте не более 100 чисел, начиная со start.
//
// **Примеры**:
// Input: start = 10, divisor = 7
// Output: Первое число: 14
//
// Input: start = 10, divisor = 3
// Output: Первое число: 12
//
// Input: start = 5, divisor = 5
// Output: Первое число: 5

func main() {
	start := 10
	divisor := 7

	// Ваш код здесь
	for i := start; i < start+100; i++ {
		if i % divisor == 0 {
			fmt.Printf("Первое число: %d\n", i)
			break
		}
	}
}
